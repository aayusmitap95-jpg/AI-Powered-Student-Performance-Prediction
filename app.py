"""Streamlit dashboard: estimated score plus separate rule-based suggestions."""
from pathlib import Path
import joblib
import pandas as pd
import streamlit as st
ROOT = Path(__file__).resolve().parent
MODEL_PATH = ROOT/"models"/"student_score_pipeline.joblib"
st.set_page_config(page_title="Student Performance AI", page_icon="🎓", layout="wide")
st.title("🎓 AI-Powered Student Performance Prediction & Learning Recommendation System")
st.caption("A learning-support prototype using synthetic demonstration data.")
if not MODEL_PATH.exists():
    st.error("Trained model not found. First run: python train_model.py")
    st.stop()
model = joblib.load(MODEL_PATH)
st.info("This tool gives an approximate score estimate for learning support only. It is not a diagnosis or a high-stakes decision tool.")
st.subheader("Enter student learning information")
with st.form("student_inputs"):
    c1,c2 = st.columns(2)
    with c1:
        study = st.slider("Study hours per week", 1, 40, 10)
        attendance = st.slider("Attendance (%)", 0, 100, 85)
        previous = st.slider("Previous exam score", 0, 100, 65)
        assignments = st.slider("Assignments completed (out of 10)", 0, 10, 7)
    with c2:
        sleep = st.slider("Average sleep hours per night", 3.0, 12.0, 7.0, 0.5)
        participation = st.slider("Class participation (1 low – 5 high)", 1, 5, 3)
        internet = st.selectbox("Internet access at home", ["Yes","No"])
        support = st.selectbox("Extra learning support", ["No","Yes"])
    submitted = st.form_submit_button("Predict estimated score")
if submitted:
    row = pd.DataFrame([{
        "study_hours_per_week":study, "attendance_percent":attendance,
        "previous_exam_score":previous, "assignments_completed":assignments,
        "sleep_hours_per_night":sleep, "class_participation":participation,
        "internet_access":internet, "extra_support":support
    }])
    estimate = float(model.predict(row)[0])
    st.subheader("Prediction result")
    st.metric("Estimated final score", f"{estimate:.1f} / 100")
    st.caption("Estimate only; actual results can differ. Model trained on synthetic data, not real student records.")
    st.subheader("Personalized learning suggestions")
    suggestions = []
    if attendance < 85: suggestions.append("Attendance is below 85%: identify barriers and aim for more consistent attendance where possible.")
    if study < 8: suggestions.append("Try a realistic weekly study timetable with short, focused sessions and breaks.")
    if previous < 60: suggestions.append("Review previous exam mistakes and revisit the foundational topics before attempting harder questions.")
    if assignments < 8: suggestions.append("Break assignments into small tasks and set earlier personal deadlines.")
    if sleep < 7: suggestions.append("Consider a consistent sleep schedule; adequate rest can support concentration.")
    if participation < 3: suggestions.append("Try asking one question per class or explaining one concept to a peer.")
    if support == "No" and previous < 65: suggestions.append("Consider asking a teacher, mentor, or study group for additional help.")
    if not suggestions: suggestions.append("Keep your current routine under review; use practice tests and spaced revision to identify gaps.")
    for item in suggestions: st.write("• " + item)
    st.caption("Recommendations are simple rules based on the inputs, not generated by the machine-learning model.")
st.divider()
st.subheader("Exploratory data analysis")
chart_cols = st.columns(2)
charts = [
    ("outputs/score_distribution.png","Score distribution"),
    ("outputs/study_hours_vs_score.png","Study hours vs score"),
    ("outputs/attendance_vs_score.png","Attendance vs score"),
    ("outputs/actual_vs_predicted.png","Test-set actual vs predicted")
]
for i,(path,label) in enumerate(charts):
    with chart_cols[i%2]:
        p = ROOT/path
        if p.exists():
            st.image(str(p), caption=label, use_container_width=True)
st.subheader("Model evaluation")
metrics_path = ROOT/"outputs"/"metrics.json"
if metrics_path.exists():
    import json
    m=json.loads(metrics_path.read_text())
    a,b,c=st.columns(3)
    a.metric("Random Forest MAE",f"{m.get('Random Forest MAE',m.get('random_forest_mae',0)):.2f}")
    b.metric("RMSE",f"{m.get('Random Forest RMSE',m.get('random_forest_rmse',0)):.2f}")
    c.metric("R²",f"{m.get('Random Forest R2',m.get('random_forest_r2',0)):.3f}")
st.caption("Data source: synthetic data generated for this educational prototype. No identifiable student records are used.")
